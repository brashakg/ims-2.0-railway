"""Refresh the marked RBAC documentation from POLICY, without starting the app.

Run from any directory: python scripts/generate_rbac_matrix.py [--check]
Only the marked section is generated; surrounding explanations are preserved.
"""

from __future__ import annotations

import argparse
from collections import Counter
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
DOCUMENT = ROOT / "docs" / "reference" / "RBAC_MATRIX.md"
BEGIN = "<!-- BEGIN GENERATED RBAC MATRIX -->"
END = "<!-- END GENERATED RBAC MATRIX -->"

sys.path.insert(0, str(ROOT / "backend"))
from api.services.rbac_policy import AUTHENTICATED, POLICY, PUBLIC  # noqa: E402


def render_section(policy) -> str:
    """Render every policy key, including slash aliases and both boolean flags."""
    rows = sorted(policy, key=lambda row: (row["path"], row["method"]))
    keys = [(row["method"], row["path"]) for row in rows]
    if len(keys) != len(set(keys)):
        raise ValueError("POLICY contains duplicate method/path keys")
    counts = Counter(
        row["allowed"] if isinstance(row["allowed"], str) else "ROLE_LIST"
        for row in rows
    )
    lines = [
        "## Gate-type summary",
        "",
        "| Gate type | Count |",
        "|---|---|",
        f"| PUBLIC (no IMS role gate) | {counts[PUBLIC]} |",
        f"| AUTHENTICATED | {counts[AUTHENTICATED]} |",
        f"| Role-gated (one or more roles) | {counts['ROLE_LIST']} |",
        f"| **Total `/api/v1` (method x path)** | **{len(rows)}** |",
        f"| ...of which `store_scoped` | {sum(bool(r.get('store_scoped')) for r in rows)} |",
        f"| ...of which `self_enforced` | {sum(bool(r.get('self_enforced')) for r in rows)} |",
        "",
        "## Full matrix (method x path -> policy entry)",
        "",
        "Generated by `scripts/generate_rbac_matrix.py`; edit POLICY, then regenerate.",
        "`AUTH` means `AUTHENTICATED`; `S` and `E` mark the registry's",
        "`store_scoped` and `self_enforced` flags. Role lists preserve the policy",
        "entry exactly; see the manual interpretation notes above.",
    ]
    previous_group = None
    for row in rows:
        group = "/".join(row["path"].split("/")[:4])
        if group != previous_group:
            lines.extend([
                "", f"### `{group}`", "",
                "| Method | Path | Allowed | S | E |",
                "|---|---|---|---|---|",
            ])
            previous_group = group
        allowed = row["allowed"]
        if allowed == AUTHENTICATED:
            cell = "AUTH"
        elif isinstance(allowed, str):
            cell = allowed
        else:
            cell = ", ".join(allowed)
        scoped = "S" if row.get("store_scoped") else ""
        enforced = "E" if row.get("self_enforced") else ""
        lines.append(f"| `{row['method']}` | `{row['path']}` | {cell} | {scoped} | {enforced} |")
    return "\n".join(lines) + "\n"


def updated_document(document: str, policy) -> str:
    """Replace one marked section; refuse malformed boundaries before writing."""
    if document.count(BEGIN) != 1 or document.count(END) != 1:
        raise ValueError("Expected exactly one BEGIN and END generated RBAC marker")
    before, rest = document.split(BEGIN)
    if END not in rest:
        raise ValueError("Generated RBAC markers are out of order")
    _, after = rest.split(END)
    return before + BEGIN + "\n\n" + render_section(policy) + "\n" + END + after


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail on drift without modifying the document")
    parser.add_argument("--document", type=Path, default=DOCUMENT, help="Markdown file with generated markers")
    args = parser.parse_args(argv)
    try:
        original = args.document.read_text(encoding="utf-8")
        updated = updated_document(original, POLICY)
    except (OSError, ValueError) as exc:
        print(f"RBAC matrix: {exc}", file=sys.stderr)
        return 2
    if updated == original:
        print(f"RBAC matrix is current ({len(POLICY)} policy rows).")
        return 0
    if args.check:
        print("RBAC matrix is stale. Run: python scripts/generate_rbac_matrix.py", file=sys.stderr)
        return 1
    args.document.write_text(updated, encoding="utf-8", newline="\n")
    print(f"Updated {args.document} ({len(POLICY)} policy rows).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
