"""Write the full RBAC matrix (every POLICY row) to a local, uncommitted file.

Run from any directory: python scripts/generate_rbac_matrix.py [--output PATH]
The output (docs/reference/RBAC_MATRIX.generated.md) is gitignored: committing
it made every route-adding PR conflict on the same file. CI guards the policy
itself (tests/test_rbac_policy.py: every live route has a POLICY row) and the
renderer (tests/test_rbac_matrix_document.py). Reading notes live in
docs/reference/RBAC_MATRIX.md.
"""

from __future__ import annotations

import argparse
from collections import Counter
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "reference" / "RBAC_MATRIX.generated.md"

sys.path.insert(0, str(ROOT / "backend"))
from api.services.rbac_policy import AUTHENTICATED, POLICY, PUBLIC  # noqa: E402


def render_section(policy) -> str:
    """Render every policy key, including slash aliases and both boolean flags."""
    rows = sorted(policy, key=lambda row: (row["path"], row["method"]))
    keys = [(row["method"], row["path"]) for row in rows]
    if len(keys) != len(set(keys)):
        raise ValueError("POLICY contains duplicate method/path keys")
    counts = Counter(
        row["allowed"] if isinstance(row["allowed"], str) else "ROLE_LIST"
        for row in rows
    )
    lines = [
        "## Gate-type summary",
        "",
        "| Gate type | Count |",
        "|---|---|",
        f"| PUBLIC (no IMS role gate) | {counts[PUBLIC]} |",
        f"| AUTHENTICATED | {counts[AUTHENTICATED]} |",
        f"| Role-gated (one or more roles) | {counts['ROLE_LIST']} |",
        f"| **Total `/api/v1` (method x path)** | **{len(rows)}** |",
        f"| ...of which `store_scoped` | {sum(bool(r.get('store_scoped')) for r in rows)} |",
        f"| ...of which `self_enforced` | {sum(bool(r.get('self_enforced')) for r in rows)} |",
        "",
        "## Full matrix (method x path -> policy entry)",
        "",
        "Generated by `scripts/generate_rbac_matrix.py` from POLICY; not committed.",
        "`AUTH` means `AUTHENTICATED`; `S` and `E` mark the registry's",
        "`store_scoped` and `self_enforced` flags. Role lists preserve the policy",
        "entry exactly; see docs/reference/RBAC_MATRIX.md for how to read them.",
    ]
    previous_group = None
    for row in rows:
        group = "/".join(row["path"].split("/")[:4])
        if group != previous_group:
            lines.extend([
                "", f"### `{group}`", "",
                "| Method | Path | Allowed | S | E |",
                "|---|---|---|---|---|",
            ])
            previous_group = group
        allowed = row["allowed"]
        if allowed == AUTHENTICATED:
            cell = "AUTH"
        elif isinstance(allowed, str):
            cell = allowed
        else:
            cell = ", ".join(allowed)
        scoped = "S" if row.get("store_scoped") else ""
        enforced = "E" if row.get("self_enforced") else ""
        lines.append(f"| `{row['method']}` | `{row['path']}` | {cell} | {scoped} | {enforced} |")
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=OUTPUT, help="Markdown file to write")
    args = parser.parse_args(argv)
    try:
        text = "# IMS 2.0 - RBAC matrix (generated)\n\n" + render_section(POLICY)
    except ValueError as exc:
        print(f"RBAC matrix: {exc}", file=sys.stderr)
        return 2
    args.output.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {args.output} ({len(POLICY)} policy rows).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
